"""One merged library for the controlled retrieval evaluation (eval/retrieval_ablation.py).

Every question of a set is searched in the same folder, so the number of files, the
term statistics and the distractors are the same for all questions and all configs.
A set lists its parts under `library:`; each part becomes a top-level folder:

    library:
      - {name: papers, source: data/real/papers}        # copied, hidden files left out
      - {name: mixed, builder: eval.retrieval_mixed}      # generated by the module's build(root)

Imports no retrieval code: the relabelling tool (eval/retrieval_relabel.py) uses this
module and must stay blind to how the system ranks.
"""
import importlib
import re
import shutil
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def normalize(text):
    """Case, width and punctuation folded away: how evidence strings are matched."""
    return re.sub(r"[\W_]+", "", unicodedata.normalize("NFKC", text).casefold())


def build(folder, parts):
    """Create every part under folder; returns folder (the library root)."""
    folder = Path(folder)
    names = [p['name'] for p in parts]
    if len(names) != len(set(names)) or any(not n or n.startswith('.') or '/' in n for n in names):
        raise ValueError(f'library part names must be distinct plain names: {names}')
    for part in parts:
        target = folder / part['name']
        if 'source' in part:
            shutil.copytree(ROOT / part['source'], target, ignore=shutil.ignore_patterns('.*'))
        elif 'builder' in part:
            importlib.import_module(part['builder']).build(target)
        else:
            raise ValueError(f"library part {part['name']} needs source or builder")
    return folder


def files(root):
    """Library files (relative, sorted), hidden files and folders left out as the index does."""
    root = Path(root)
    return sorted(p.relative_to(root).as_posix() for p in root.rglob('*')
                  if p.is_file() and not any(s.startswith('.') for s in p.relative_to(root).parts))
